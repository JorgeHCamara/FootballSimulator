/**
 * Builds every domestic league's starting ratings and match parameters for
 * one season, and writes them to src/data/priors/<year>.ts.
 *
 *   NODE_USE_ENV_PROXY=1 node scripts/build-priors.ts 2026   (or: npm run priors -- 2026)
 *
 * Run it once a season has its clubs on ESPN (each league's clubs come from
 * the new season's fixtures). For each league (see priorsLib.ts):
 * - each club's starting rating, from last season: the same league's
 *   rating pulled partway back to average, a promoted club's rating below
 *   turned into a below-average one, a relegated club's the reverse, or a
 *   below-average default without data; rescaled to average 1;
 * - rho, the Dixon–Coles dependence of low scores, by maximum likelihood
 *   over last season's and this season's games;
 * - each returning club's home/away split relative to the league's, from
 *   the same games, shrunk hard to the league's and clamped to ±30%.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LEAGUES } from "../src/config/leagues.ts";
import { ratingHalfLife } from "../src/engine/ratings.ts";
import { buildLeaguePriors } from "./priorsLib.ts";

const year = Number(process.argv[2]);
if (!Number.isInteger(year) || year < 2000) {
  console.error("Usage: node scripts/build-priors.ts <season start year, e.g. 2026>");
  process.exit(1);
}

const entries: string[] = [];
for (const league of LEAGUES.filter((l) => !l.continental)) {
  try {
    // Last season's later games count a bit more when recency weighting is on.
    const priors = await buildLeaguePriors(league, year, { halfLife: ratingHalfLife(league) });
    if (!priors) {
      console.warn(`${league.code}: no ${year} clubs on ESPN yet, skipped`);
      continue;
    }
    const { counts } = priors;
    console.log(
      `${league.code}: ${priors.clubs.size} clubs (${counts.returning} returning, ${counts.promoted} promoted, ${counts.relegated} relegated, ${counts.unknown} unknown); rho ${priors.rho} from ${priors.rhoMatches} games; ${priors.home.size} home splits`,
    );
    entries.push(
      [
        `  ${league.code}: {`,
        `    rho: ${priors.rho},`,
        `    clubs: {`,
        ...[...priors.clubs].map(([id, s]) => `      "${id}": [${s.attack}, ${s.defence}],`),
        `    },`,
        `    home: {`,
        ...[...priors.home].map(([id, k]) => `      "${id}": ${k},`),
        `    },`,
        `  },`,
      ].join("\n"),
    );
  } catch (error) {
    console.warn(`${league.code}: failed, skipped:`, error instanceof Error ? error.message : error);
  }
}

const dir = join(dirname(fileURLToPath(import.meta.url)), "../src/data/priors");
writeFileSync(
  join(dir, `${year}.ts`),
  `// Generated by \`npm run priors -- ${year}\` (scripts/build-priors.ts) on ${new Date().toISOString().slice(0, 10)}, from ESPN's results.
// For the season starting in ${year}, by league:
// - rho: Dixon–Coles dependence of low scores (negative: more 0–0 and 1–1), from the ${year - 1} season's and this season's games;
// - clubs: starting ratings by ESPN club id, [attack, defence] relative to the league average (attack above 1 scores
//   more, defence above 1 concedes more), from the ${year - 1} season;
// - home: each returning club's home/away split relative to the league's (1 = the league's home advantage).
// Don't edit by hand: rerun the script.
import type { PriorSeason } from "../../lib/priors.ts";

const PRIORS: PriorSeason = {
${entries.join("\n")}
};

export default PRIORS;
`,
);
// The index lists every season's file.
const years = readdirSync(dir)
  .map((f) => /^(\d{4})\.ts$/.exec(f)?.[1])
  .filter((y): y is string => Boolean(y))
  .sort();
writeFileSync(
  join(dir, "index.ts"),
  `// Generated by scripts/build-priors.ts: every season's starting ratings, by the year it starts.
import type { PriorSeason } from "../../lib/priors.ts";
${years.map((y) => `import priors${y} from "./${y}.ts";`).join("\n")}

export const PRIOR_SEASONS: Readonly<Record<number, PriorSeason>> = {
${years.map((y) => `  ${y}: priors${y},`).join("\n")}
};
`,
);
console.log(`Wrote src/data/priors/${year}.ts (${entries.length} leagues).`);
